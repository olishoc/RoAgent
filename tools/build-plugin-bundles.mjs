import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function read(relativePath) {
  return readFileSync(path.join(root, relativePath), "utf8").replace(/\r\n/g, "\n").trimEnd();
}

function write(relativePath, text) {
  const target = path.join(root, relativePath);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, `${text.replace(/\r\n/g, "\n").trimEnd()}\n`);
}

function versionFrom(source, fallback) {
  return source.match(/PLUGIN_VERSION\s*=\s*"([^"]+)"/)?.[1] ?? fallback;
}

function wrapModule(name, source) {
  return `local function load_${name}()\n${source}\nend`;
}

function buildBridgeBundle() {
  const bridgeUtils = read("plugin/BridgeUtils.lua");
  const connectionManager = read("plugin/ConnectionManager.lua");
  let entry = read("plugin/StudioLinkBridgeOnly.lua");
  entry = entry.replace(
    'local Utils = require(script:WaitForChild("BridgeUtils"))',
    "local Utils = load_BridgeUtils()",
  );
  entry = entry.replace(
    'local ConnectionManager = require(script:WaitForChild("ConnectionManager"))',
    "local ConnectionManager = load_ConnectionManager()",
  );

  return [
    "-- StudioLink bridge-only bundled Roblox Studio plugin",
    "-- HTTP-primary build. Paste this whole file as a local plugin script.",
    "-- Generated from plugin/StudioLinkBridgeOnly.lua; do not hand-edit.",
    "",
    wrapModule("BridgeUtils", bridgeUtils),
    "",
    wrapModule("ConnectionManager", connectionManager),
    "",
    entry,
  ].join("\n");
}

const bridgeBundle = buildBridgeBundle();
const legacyBundle = read("plugin/StudioLinkPlugin_Bundled.lua");
const bridgeVersion = versionFrom(bridgeBundle, "2.0.0-bridge");
const legacyVersion = versionFrom(legacyBundle, "1.0.10");

write("plugin/StudioLinkBridgeOnly_Bundled.lua", bridgeBundle);
write(
  "website-worker/src/pluginBundle.ts",
  [
    "// Generated by tools/build-plugin-bundles.mjs.",
    'export const PLUGIN_BUNDLE_FILE_NAME = "StudioLinkPlugin_Bundled.lua";',
    `export const PLUGIN_BUNDLE_VERSION = ${JSON.stringify(bridgeVersion)};`,
    `export const PLUGIN_BUNDLE = ${JSON.stringify(bridgeBundle)};`,
    "",
    'export const LEGACY_PLUGIN_BUNDLE_FILE_NAME = "StudioLinkPlugin_LegacyUI.lua";',
    `export const LEGACY_PLUGIN_BUNDLE_VERSION = ${JSON.stringify(legacyVersion)};`,
    `export const LEGACY_PLUGIN_BUNDLE = ${JSON.stringify(legacyBundle)};`,
  ].join("\n"),
);

console.log(`Generated bridge plugin ${bridgeVersion} and legacy UI plugin ${legacyVersion}.`);
